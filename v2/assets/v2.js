"use strict";
(() => {
  const scenarios = window.LAZY_DOGGY_V2_SCENARIOS;
  const byId = id => document.getElementById(id);
  const scenarioButtons = [...document.querySelectorAll("[data-scenario]")];
  const journeyNodes = [...document.querySelectorAll("[data-node]")];
  const refs = {
    "ref-android-build": "B / Android 命令行构建",
    "ref-android-test": "T / Android 模拟器",
    "ref-android-acceleration": "H / 模拟器加速条件",
    "ref-android-update": "U / Android 安装与签名",
    "ref-security": "S / 权限与安全设计"
  };
  let activeScenario = "habit";
  let stepIndex = 0;
  let timer = null;
  let gifPlaying = false;
  // Fixed illustration values. These are not generated by any strategy.
  const syntheticSeries = Object.freeze([51, 45, 48, 58, 46, 53, 43, 56, 50, 46, 54, 48]);
  const setText = (id, text) => { byId(id).textContent = text; };
  function stopGif() {
    if (gifPlaying) byId("backtest-flow-image").setAttribute("src", "assets/backtest-flow.svg");
    gifPlaying = false;
    setText("gif-toggle", "播放动图");
    byId("gif-toggle").setAttribute("aria-pressed", "false");
  }
  function prepareSyntheticChart() {
    const points = syntheticSeries.map((value, index) => [62 + index * 628 / 11, 238 - (value - 20) * 200 / 60]);
    byId("backtest-chart-line").setAttribute("points", points.map(point => point.map(value => value.toFixed(2)).join(",")).join(" "));
    const fragment = document.createDocumentFragment();
    points.forEach(([cx, cy]) => {
      const point = document.createElementNS("http://www.w3.org/2000/svg", "circle");
      point.setAttribute("cx", cx.toFixed(2));
      point.setAttribute("cy", cy.toFixed(2));
      point.setAttribute("r", "4");
      fragment.append(point);
    });
    byId("backtest-chart-points").replaceChildren(fragment);
  }
  function pause() {
    if (timer !== null) { window.clearInterval(timer); timer = null; }
    setText("play-button", "播放流程");
    byId("play-button").setAttribute("aria-pressed", "false");
  }
  function snapshot(scenario, index) {
    const state = {
      build: ["等待任务", "代码修改和构建在隔离 Linux 环境进行。"],
      test: ["尚未测试", scenario.testName === "Android 模拟器" ? "安装构建产物，再验证实际运行。" : "检查手机、电脑布局和交互。"],
      release: ["尚未发布", "测试通过也不等于已经授权发布。"],
      artifactStatus: "还没有构建文件", canResult: false,
      chartReady: false, chartStatus: "先完成数据与脚本检查"
    };
    for (const step of scenario.steps.slice(0, index + 1)) {
      for (const key of Object.keys(state)) {
        if (Object.hasOwn(step, key)) state[key] = step[key];
      }
    }
    return state;
  }
  function renderSteps(scenario) {
    const fragment = document.createDocumentFragment();
    scenario.steps.forEach((step, index) => {
      const button = document.createElement("button");
      button.type = "button";
      button.dataset.step = String(index);
      button.setAttribute("aria-label", `第 ${index + 1} 步：${step.title}`);
      const number = document.createElement("span");
      number.textContent = String(index + 1).padStart(2, "0");
      const label = document.createElement("b");
      label.textContent = step.title;
      button.append(number, label);
      fragment.append(button);
    });
    byId("step-list").replaceChildren(fragment);
  }
  function render() {
    const scenario = scenarios[activeScenario];
    const step = scenario.steps[stepIndex];
    const state = snapshot(scenario, stepIndex);
    scenarioButtons.forEach(button => button.setAttribute("aria-pressed", String(button.dataset.scenario === activeScenario)));
    setText("scenario-title", scenario.title);
    setText("scenario-description", scenario.description);
    setText("phone-wish", scenario.wish);
    setText("phone-reply", step.reply);
    setText("device-caption", scenario.deviceCaption || (activeScenario === "website" ? "你不用守在电脑前。开发、测试和发布在服务器安排。" : "你不用守在电脑前。测试、签名和发布仍在服务器完成。"));
    setText("artifact-name", scenario.artifact);
    setText("artifact-status", state.artifactStatus);
    setText("result-button", scenario.resultButton);
    byId("result-button").disabled = !state.canResult;
    setText("test-node-title", scenario.testName);
    setText("test-kicker", scenario.testKicker);
    setText("step-counter", `${String(stepIndex + 1).padStart(2, "0")} / ${scenario.steps.length}`);
    setText("step-badge", step.badge);
    setText("step-title", step.title);
    setText("step-description", step.text);
    setText("step-guard", step.guard);
    setText("receipt-id", scenario.receipt);
    ["build", "test", "release"].forEach(area => {
      setText(`${area}-status`, state[area][0]);
      setText(`${area}-detail`, state[area][1]);
    });
    byId("receipt-button").disabled = stepIndex === 0;
    const ref = byId("step-reference");
    ref.replaceChildren();
    if (step.ref && Object.hasOwn(refs, step.ref)) {
      const sup = document.createElement("sup");
      sup.className = "citation";
      const anchor = document.createElement("a");
      anchor.href = `#${step.ref}`;
      anchor.setAttribute("aria-label", `参考 ${refs[step.ref]}`);
      anchor.textContent = `[${refs[step.ref]}]`;
      sup.append(anchor);
      ref.append(sup);
    }
    const touchedNodes = new Set(scenario.steps.slice(0, stepIndex).map(item => item.node));
    journeyNodes.forEach(node => {
      const current = node.dataset.node === step.node;
      node.classList.toggle("is-active", current);
      node.classList.toggle("is-done", !current && touchedNodes.has(node.dataset.node));
      if (current) node.setAttribute("aria-current", "step");
      else node.removeAttribute("aria-current");
    });
    const range = byId("step-range");
    range.max = String(scenario.steps.length - 1);
    range.value = String(stepIndex);
    range.setAttribute("aria-valuetext", `第 ${stepIndex + 1} 步，共 ${scenario.steps.length} 步：${step.title}`);
    setText("range-label", `${stepIndex + 1} / ${scenario.steps.length}`);
    byId("previous-button").disabled = stepIndex === 0;
    byId("next-button").disabled = stepIndex === scenario.steps.length - 1;
    byId("step-list").querySelectorAll("button").forEach(button => button.setAttribute("aria-pressed", String(Number(button.dataset.step) === stepIndex)));
    byId("backtest-chart").hidden = activeScenario !== "backtest";
    setText("chart-status", state.chartStatus);
    byId("backtest-chart-line").toggleAttribute("hidden", !state.chartReady);
    byId("backtest-chart-points").toggleAttribute("hidden", !state.chartReady);
    byId("chart-empty").toggleAttribute("hidden", state.chartReady);
    setText("chart-description", state.chartReady ? "页面预设十二个无单位数字的合成教学图，不是策略计算或实际回测结果。" : "当前尚未生成图表，需到第七步才展示预设的合成教学序列。没有实际回测。");
    byId("gif-toggle").disabled = activeScenario !== "backtest";
  }
  function jump(index, announcement = null) {
    pause();
    stepIndex = Math.max(0, Math.min(scenarios[activeScenario].steps.length - 1, index));
    render();
    if (announcement !== null) setText("interaction-status", announcement);
  }
  scenarioButtons.forEach(button => button.addEventListener("click", () => {
    if (!Object.hasOwn(scenarios, button.dataset.scenario)) return;
    activeScenario = button.dataset.scenario;
    pause();
    stopGif();
    stepIndex = 0;
    renderSteps(scenarios[activeScenario]);
    render();
    setText("interaction-status", "已切换示例并暂停。这里没有提交新的任务，可以按步查看。");
  }));
  byId("play-button").addEventListener("click", () => {
    if (timer !== null) { pause(); setText("interaction-status", "已暂停，只停止教学播放，不会中断任何真实任务。"); return; }
    const last = scenarios[activeScenario].steps.length - 1;
    if (stepIndex === last) { stepIndex = 0; render(); }
    setText("play-button", "暂停播放");
    byId("play-button").setAttribute("aria-pressed", "true");
    setText("interaction-status", "正在播放本地教学流程，每步 3.5 秒。可随时暂停、拖动或切换示例。");
    timer = window.setInterval(() => {
      stepIndex = Math.min(last, stepIndex + 1);
      render();
      if (stepIndex === last) { pause(); setText("interaction-status", "教学流程播完了。结果按钮只模拟动作，不会下载、安装、回测或发布。"); }
    }, 3500);
  });
  byId("previous-button").addEventListener("click", () => jump(stepIndex - 1, "已回到上一步，播放已暂停。"));
  byId("next-button").addEventListener("click", () => jump(stepIndex + 1, "已到下一步，播放已暂停。"));
  byId("restart-button").addEventListener("click", () => jump(0, "已回到开始。这只重置教学画面，没有重放任何请求。"));
  byId("step-range").addEventListener("input", event => jump(Number(event.target.value), "已拖动到所选步骤，播放已暂停。"));
  byId("step-list").addEventListener("click", event => {
    const button = event.target.closest("button[data-step]");
    if (button) jump(Number(button.dataset.step), "已跳到所选步骤，播放已暂停。");
  });
  byId("receipt-button").addEventListener("click", () => {
    pause();
    setText("interaction-status", `模拟只读查看 ${scenarios[activeScenario].receipt}：仍是第 ${stepIndex + 1} 步，不重新提交需求。本页没有网络查询。`);
  });
  byId("result-button").addEventListener("click", () => {
    if (byId("result-button").disabled) return;
    pause();
    setText("interaction-status", scenarios[activeScenario].resultNotice);
  });
  byId("gif-toggle").addEventListener("click", () => {
    if (activeScenario !== "backtest") return;
    if (gifPlaying) {
      stopGif();
      setText("interaction-status", "动图已停止并回到静态图，没有暂停到同一帧。它只演示完整流程，不触发真实回测。");
    } else {
      byId("backtest-flow-image").setAttribute("src", "assets/backtest-flow.gif");
      gifPlaying = true;
      setText("gif-toggle", "停止动图");
      byId("gif-toggle").setAttribute("aria-pressed", "true");
      setText("interaction-status", "正在播放合成教学动图；曲线不是实际回测结果，动图不调用 API、不回测、不部署。");
    }
  });
  document.addEventListener("visibilitychange", () => { if (document.hidden) { pause(); stopGif(); } });
  prepareSyntheticChart();
  renderSteps(scenarios[activeScenario]);
  byId("play-button").setAttribute("aria-pressed", "false");
  render();
})();
